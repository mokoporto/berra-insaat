/* ADA/PARSEL SORGULAMA                                                */
/* ------------------------------------------------------------------ */
export function queryParcel(ada: string, parsel: string): KatType | 'empty' | 'notfound' {
  const key = `${ada.trim()}-${parsel.trim()}`
  if (Object.keys(PARCEL_MAP).length === 0) return 'empty'
  return PARCEL_MAP[key] ?? 'notfound'
}
